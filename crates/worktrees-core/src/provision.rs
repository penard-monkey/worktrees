    /// Every fs test gets its OWN port window. These tests really do bind, and
    /// `cargo test` runs them in parallel — two tests probing one port make each
    /// other look busy, which is a flake, not a finding.
    static NEXT_BASE: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(34_001);

    struct Tmp(PathBuf, u32);
    impl Tmp {
        fn new(tag: &str) -> Tmp {
            let d = std::env::temp_dir().join(format!(
                "wtprov-{tag}-{}-{:?}",
                std::process::id(),
                std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos()
            ));
            fs::create_dir_all(d.join(".worktrees")).unwrap();
            Tmp(d, NEXT_BASE.fetch_add(1_000, std::sync::atomic::Ordering::Relaxed))
        }
        fn port(&self, off: u32, k: u32) -> u32 {
            self.1 + off + 100 * k
        }
        fn wt(&self, slug: &str) -> PathBuf {
            let p = self.0.join(".worktrees").join(slug);
            fs::create_dir_all(&p).unwrap();
            p
        }
        fn cfg(&self) -> ProjectConfig {
            ProjectConfig {
                files: Vec::new(),
                ports: Some(ports(100, 3, &[("API", self.1), ("PG", self.1 + 500)])),
                compose: Some(Compose {
                    files: vec![RelPath::parse("docker-compose.worktree.yml").unwrap()],
                    project: "{prefix}-wt-{slug}".into(),
                }),
                project: Default::default(),
            }
        }
        fn run_cfg(&self, slug: &str, reallocate: bool, cfg: &ProjectConfig) -> Result<Outcome, ProvisionError> {
            let wt = self.wt(slug);
            let wt_root = self.0.join(".worktrees");
            provision(
                &Request {
                    main_root: &self.0,
                    wt_root: &wt_root,
                    wt: &wt,
                    prefix: "proj",
                    slug,
                    reallocate,
                },
                cfg,
            )
        }
        fn run(&self, slug: &str, reallocate: bool) -> Result<Outcome, ProvisionError> {
            self.run_cfg(slug, reallocate, &self.cfg())
        }
    }
    impl Drop for Tmp {
        fn drop(&mut self) {
            let _ = fs::remove_dir_all(&self.0);
        }
    }

