//! `[ports]` + `[compose]` — slot allocation, the `.worktree.env` wire format,
//! and the one piece of docker argv the tool assembles (proposal §3, §5, §6).
//!
//! Three layers, same discipline as `materialize.rs`:
//!
//! ```text
//! select_slot / render_env / compose_project_name   PURE — the whole test surface
//! scan / port_free / read_env                       the only filesystem+socket READS
//! provision                                         the only filesystem WRITE
//! ```
//!
//! ⚠ **The slot is DERIVED, never stored in `.worktrees.places.json`** (§6). The
//! store's contract is sticky user intent that survives the worktree being gone,
//! and `remove_one` never calls `store::edit` — so a stored slot would leak on
//! every `rm` and turn `max_slots` into a silent exhaustion bug months later.
//! Deriving it from each place's own `.worktree.env` means there is **no release
//! step at all**: `rm` deletes the directory, the env file goes with it, and the
//! next scan sees the hole.
//!
//! ⚠ **`.worktree.env` is a public wire format, not an internal artifact** (§3).
//! Six consumers read it and at least one does `set -a; . .worktree.env`, so
//! every emitted line is sourced AS SHELL. Two things follow, and both are
//! load-bearing:
//!
//! - `WORKTREE_SLOT` is emitted even though the tool could re-derive it. A
//!   consumer keys a behavior off its mere presence; dropping it as "internal
//!   state" reintroduces a bug that repo already debugged once.
//! - The variable NAMES are the contract, and a name that is not a valid POSIX
//!   shell name emits a line that *executes* instead of assigning. `lint_ports`
//!   (`projcfg.rs`) already rejects those at parse time — [`render_env`] asserts
//!   it again rather than trusting it silently, because the two are separated by
//!   a module boundary and a future parser change must not be able to open this
//!   quietly.
//!
//! ⚠ **A hand-edited `.worktree.env` wins.** Allocation never rewrites an
//! existing `WORKTREE_SLOT` without `--reallocate`: it is the file the running
//! stack sources, and the tool disagreeing with it would be the tool lying. The
//! same holds for `COMPOSE_PROJECT_NAME` — it names the containers that are
//! actually up, so a `[compose] project` template that changed since does not
//! move it; `doctor` reports the drift (`Code::ComposeDrift`) instead.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::fs;
use std::io;
use std::net::{Ipv4Addr, TcpListener};
use std::path::{Path, PathBuf};
use std::process::Command;

