// deliberately stay Unicode: they sit inline with tabular text, not on buttons.
// The one exception is the nav row's AGENT mark (`ClaudeMark` / `OpenAIMark`
// below): David's call, logos over glyphs, because which agent is live is a
// question of identity, and a glyph standing in for a brand (✻, >_) had to be
